export function pickProverbs(n = 2) {
  const pool = [...FA_PROVERBS];
  const out = [];
  const k = Math.min(n, pool.length);
  for (let i = 0; i < k; i++) {
    out.push(pool.splice(Math.floor(Math.random() * pool.length), 1)[0]);
  }
  return out;
}
